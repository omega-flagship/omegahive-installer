import { describe, expect, it, vi } from 'vitest'

/**
 * Notices at rest (R1.1 #7; Codex 3 Nov): a toast whose time runs out while the shell rests is parked, not dropped; on
 * wake every parked toast gets a fresh time, so they all appear; outside rest toasts expire as before; an identity change
 * drops the parked ones. INVENTED notices, fake timers.
 */
vi.stubGlobal('window', { location: { hash: '#/', search: '', pathname: '/' }, matchMedia: () => ({ matches: false }), addEventListener() {}, removeEventListener() {}, localStorage: { getItem: () => null, setItem() {}, removeItem() {} } })
const { useHive, laneAfter, dropParkedNotices, noticeBookkeeping, removeToasts, forgetAllNotices } = await import('../store/store')
const { usePhase } = await import('./phase')
await import('./restNotices')

describe('notices wait for the wake', () => {
  it('a notice whose time runs out at rest stays, and gets a fresh time on wake', () => {
    vi.useFakeTimers()
    usePhase.setState({ phased: true, phase: 'rest' })
    useHive.getState().toast({ tone: 'error', title: 'Build failed', body: 'x' } as never)
    vi.advanceTimersByTime(60_000)
    expect(useHive.getState().toasts.map((t) => t.title)).toContain('Build failed')
    usePhase.setState({ phase: 'awake' })
    vi.advanceTimersByTime(5_000)
    expect(useHive.getState().toasts.map((t) => t.title)).toContain('Build failed')
    vi.advanceTimersByTime(2_000)
    expect(useHive.getState().toasts.map((t) => t.title)).not.toContain('Build failed')
    vi.useRealTimers()
  })
  it('outside rest a notice expires on its normal time', () => {
    vi.useFakeTimers()
    usePhase.setState({ phased: true, phase: 'awake' })
    useHive.getState().toast({ tone: 'info', title: 'Saved', body: 'y' } as never)
    vi.advanceTimersByTime(3_600)
    expect(useHive.getState().toasts.map((t) => t.title)).not.toContain('Saved')
    vi.useRealTimers()
  })
})

describe('Dot R3.1: overflow, stale entries, identity', () => {
  it('three same-group approval outcomes under lane pressure leave only live notice bookkeeping', () => {
    vi.useFakeTimers()
    forgetAllNotices(); useHive.setState({ toasts: [] })
    usePhase.setState({ phased: true, phase: 'rest' })
    const liveIds = () => useHive.getState().toasts.map(t => t.id).sort((a, b) => a - b)
    const sorted = (ids: number[]) => [...ids].sort((a, b) => a - b)
    for (const [index, title] of ['An approval is still waiting', 'Check your approval answer', 'Your answer is ready'].entries()) {
      for (let n = 0; n < 4; n++) useHive.getState().toast({ tone: n % 2 ? 'info' : 'error', title: `Pressure ${index}/${n}` })
      useHive.getState().toast({ tone: 'info', group: 'approval-return:synthetic', title, ttl: 8000 })
      expect(useHive.getState().toasts.filter(t => t.group === 'approval-return:synthetic').map(t => t.title)).toEqual([title])
      expect(sorted(noticeBookkeeping().parked)).toEqual(liveIds())
      expect(noticeBookkeeping().timed).toEqual([])
    }
    vi.advanceTimersByTime(60_000)
    expect(sorted(noticeBookkeeping().parked)).toEqual(liveIds())
    usePhase.setState({ phase: 'awake' })
    expect(noticeBookkeeping().parked).toEqual([])
    expect(sorted(noticeBookkeeping().timed)).toEqual(liveIds())
    expect(useHive.getState().toasts.find(t => t.group === 'approval-return:synthetic')?.title).toBe('Your answer is ready')
    vi.advanceTimersByTime(9000)
    expect([useHive.getState().toasts, noticeBookkeeping().parked, noticeBookkeeping().timed]).toEqual([[], [], []])
    vi.useRealTimers()
  })
  it('at rest an error is never evicted: rest, one error, five infos, wake: the error is drawn', () => {
    vi.useFakeTimers()
    useHive.setState({ toasts: [] })
    usePhase.setState({ phased: true, phase: 'rest' })
    useHive.getState().toast({ tone: 'error', title: 'Deploy failed', body: 'e' } as never)
    for (let i = 0; i < 5; i++) useHive.getState().toast({ tone: 'info', title: `Note ${i}`, body: String(i) } as never)
    vi.advanceTimersByTime(30_000)
    usePhase.setState({ phase: 'awake' })
    expect(useHive.getState().toasts.map((t) => t.title)).toContain('Deploy failed')
    expect(useHive.getState().toasts.length).toBe(4)
    vi.advanceTimersByTime(7_000)
    expect(useHive.getState().toasts).toEqual([])
    vi.useRealTimers()
  })
  it('laneAfter: outside rest the oldest goes; at rest only non-errors go, and errors past 4 stay', () => {
    const t = (id: number, tone = 'info') => ({ id, tone })
    expect(laneAfter([t(1, 'error'), t(2), t(3), t(4)], false).lane.map((x) => x.id)).toEqual([2, 3, 4])
    expect(laneAfter([t(1, 'error'), t(2), t(3), t(4)], true).lane.map((x) => x.id)).toEqual([1, 3, 4])
    expect(laneAfter([t(1, 'error'), t(2, 'error'), t(3, 'error'), t(4, 'error')], true).lane.length).toBe(4)
  })
  it('a dismissed or replaced notice leaves no parked entry: wake arms only notices still shown', () => {
    vi.useFakeTimers()
    useHive.setState({ toasts: [] })
    usePhase.setState({ phased: true, phase: 'rest' })
    for (let i = 0; i < 20; i++) useHive.getState().toast({ tone: 'info', title: 'Retrying', body: 'loader', group: 'loader' } as never)
    vi.advanceTimersByTime(10_000)
    expect(useHive.getState().toasts.length).toBe(1)
    const before = vi.getTimerCount()
    usePhase.setState({ phase: 'awake' })
    expect(vi.getTimerCount() - before).toBe(1)
    vi.useRealTimers()
  })
  it('an identity change clears the earlier notices, their timers and parked entries', () => {
    vi.useFakeTimers()
    useHive.setState({ toasts: [] })
    usePhase.setState({ phased: true, phase: 'rest' })
    useHive.getState().toast({ tone: 'error', title: 'Old person', body: 'x' } as never)
    vi.advanceTimersByTime(10_000)
    dropParkedNotices()
    expect(useHive.getState().toasts).toEqual([])
    expect(vi.getTimerCount()).toBe(0)
    usePhase.setState({ phase: 'awake' })
    vi.advanceTimersByTime(10_000)
    expect(useHive.getState().toasts).toEqual([])
    vi.useRealTimers()
  })
})

describe('Kimi R3.1: no refilled time; the bookkeeping only holds notices that exist', () => {
  const invariant = () => { const ids = new Set(useHive.getState().toasts.map((t) => t.id)); const b = noticeBookkeeping(); return [...b.parked, ...b.timed].every((id) => ids.has(id)) }
  it('rest → wake → rest keeps the time left: a notice half seen resumes with its remainder, not its whole time', () => {
    vi.useFakeTimers()
    useHive.setState({ toasts: [] })
    usePhase.setState({ phased: true, phase: 'awake' })
    useHive.getState().toast({ tone: 'error', title: 'Half seen', body: 'h' } as never)
    vi.advanceTimersByTime(4_000)
    usePhase.setState({ phase: 'rest' })
    vi.advanceTimersByTime(60_000)
    usePhase.setState({ phase: 'awake' })
    vi.advanceTimersByTime(1_900)
    expect(useHive.getState().toasts.map((t) => t.title)).toContain('Half seen')
    vi.advanceTimersByTime(200)
    expect(useHive.getState().toasts.map((t) => t.title)).not.toContain('Half seen')
    vi.useRealTimers()
  })
  it('after dismiss, replace, evict, rest, wake and an identity change, every parked or timed id is a shown notice', () => {
    vi.useFakeTimers()
    useHive.setState({ toasts: [] })
    usePhase.setState({ phased: true, phase: 'awake' })
    const say = (title: string, extra = {}) => useHive.getState().toast({ tone: 'info', title, body: title, ...extra } as never)
    say('a'); say('b', { group: 'g' }); say('c', { group: 'g' }); expect(invariant()).toBe(true)
    usePhase.setState({ phase: 'rest' }); for (const x of ['d', 'e', 'f', 'g', 'h']) say(x); expect(invariant()).toBe(true)
    useHive.getState().dismissToast(useHive.getState().toasts[0].id); expect(invariant()).toBe(true)
    usePhase.setState({ phase: 'awake' }); expect(invariant()).toBe(true)
    vi.advanceTimersByTime(10_000); expect(invariant()).toBe(true)
    usePhase.setState({ phase: 'rest' }); say('i'); dropParkedNotices(); expect(invariant()).toBe(true)
    expect(noticeBookkeeping()).toEqual({ parked: [], timed: [] })
    vi.useRealTimers()
  })
})

describe('Dot R3.1 follow-up: a long rest stays bounded; every removal keeps the bookkeeping', () => {
  const ids = () => new Set(useHive.getState().toasts.map((t) => t.id))
  const clean = () => { const b = noticeBookkeeping(); return [...b.parked, ...b.timed].every((id) => ids().has(id)) }
  it('six errors in one rest: the newest three stay, the rest are one summary said on wake', () => {
    vi.useFakeTimers()
    useHive.setState({ toasts: [] }); forgetAllNotices()
    usePhase.setState({ phased: true, phase: 'rest' })
    for (let i = 1; i <= 6; i++) useHive.getState().toast({ tone: 'error', title: `Error ${i}`, body: String(i) } as never)
    const titles = useHive.getState().toasts.map((t) => t.title)
    expect(titles).toEqual(['3 more problems while you were away', 'Error 4', 'Error 5', 'Error 6'])
    expect(clean()).toBe(true)
    usePhase.setState({ phase: 'awake' })
    expect(useHive.getState().toasts.length).toBe(4)
    vi.advanceTimersByTime(10_000)
    expect(useHive.getState().toasts).toEqual([])
    vi.useRealTimers()
  })
  it('removeToasts (the power-up path) and forgetAllNotices (the session clears) leave no bookkeeping behind', () => {
    vi.useFakeTimers()
    useHive.setState({ toasts: [] }); forgetAllNotices()
    usePhase.setState({ phased: true, phase: 'awake' })
    for (const x of ['a', 'b', 'c']) useHive.getState().toast({ tone: 'info', title: x, body: x } as never)
    const keep = useHive.getState().toasts[0].id
    removeToasts((t) => t.id > keep)
    expect(useHive.getState().toasts.map((t) => t.id)).toEqual([keep])
    expect(clean()).toBe(true)
    expect(noticeBookkeeping().timed).toEqual([keep])
    forgetAllNotices(); useHive.setState({ toasts: [] })
    expect(noticeBookkeeping()).toEqual({ parked: [], timed: [] })
    vi.useRealTimers()
  })
  it('a group replaces its own earlier notice, an error included (the newest word of a retrying loader counts)', () => {
    vi.useFakeTimers()
    useHive.setState({ toasts: [] }); forgetAllNotices()
    usePhase.setState({ phased: true, phase: 'awake' })
    useHive.getState().toast({ tone: 'error', title: 'Could not load', body: 'x', group: 'loader' } as never)
    useHive.getState().toast({ tone: 'info', title: 'Loaded', body: 'y', group: 'loader' } as never)
    expect(useHive.getState().toasts.map((t) => t.title)).toEqual(['Loaded'])
    expect(clean()).toBe(true)
    vi.useRealTimers()
  })
})
